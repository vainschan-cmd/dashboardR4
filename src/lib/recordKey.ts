/**
 * Deterministic record identity for imported performance records.
 *
 * Why this exists
 * ---------------
 * Imported record IDs used to be built as
 * `rec_imp_<year>_<month>_<branch>_<indicator>_<Date.now()>_<rowIndex>`. The
 * timestamp and row index meant the same spreadsheet imported twice produced
 * two different IDs, so `INSERT OR REPLACE` had nothing to match and every
 * re-upload silently duplicated the period. Two imports of a 40-row file left
 * 80 rows and the dashboard double-counted revenue.
 *
 * A performance record is uniquely identified by its natural key:
 *   (year, month, branch, indicator)
 * A branch reports one value per indicator per month — that is the grain of the
 * business fact. Deriving the ID from that key makes re-imports idempotent: the
 * second import updates the same row instead of adding a twin.
 *
 * Department is deliberately excluded: an indicator already belongs to exactly
 * one department, so including it adds no discriminating power and would let a
 * mis-detected department create a duplicate.
 */

export interface RecordNaturalKey {
  year: number;
  month: number;
  /** Canonical branch code (e.g. `R01`), not the internal `term_*` id. */
  branchCode: string;
  /** Indicator code (e.g. `FIN-01`). */
  indicatorCode: string;
}

/** Normalise a component for use inside an id: lower-case, no separators. */
function slug(value: string): string {
  return String(value || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Build the stable primary key for an imported record.
 *
 * Example: `{ year: 2026, month: 9, branchCode: 'R01', indicatorCode: 'FIN-01' }`
 * → `rec_imp_2026_09_r01_fin-01`
 */
export function buildRecordKey(key: RecordNaturalKey): string {
  const year = Number(key.year);
  const month = Number(key.month);
  const safeYear = Number.isFinite(year) ? year : 0;
  const safeMonth = Number.isFinite(month) ? month : 0;
  return `rec_imp_${safeYear}_${String(safeMonth).padStart(2, '0')}_${slug(key.branchCode)}_${slug(key.indicatorCode)}`;
}

/** True when an id was generated by `buildRecordKey` (i.e. it is reproducible). */
export function isDeterministicRecordId(id: string): boolean {
  return /^rec_imp_\d{4}_\d{2}_/.test(String(id || ''));
}

/**
 * Compare the fields that define the *value* of a record.
 *
 * Used to decide whether a re-import actually changes anything. When nothing
 * changed, the existing row is left untouched — including its verification
 * status. Without this check, re-importing an already-approved file would reset
 * it to `pending_verification` and force the approver to redo their work.
 */
export interface ComparableRecordValues {
  target: number;
  realization: number;
  unit?: string | null;
}

export function hasValueChanged(
  incoming: ComparableRecordValues,
  existing: ComparableRecordValues
): boolean {
  const numericEqual = (a: number, b: number) =>
    Math.abs(Number(a || 0) - Number(b || 0)) < 1e-9;
  if (!numericEqual(incoming.target, existing.target)) return true;
  if (!numericEqual(incoming.realization, existing.realization)) return true;
  return String(incoming.unit ?? '').trim() !== String(existing.unit ?? '').trim();
}
